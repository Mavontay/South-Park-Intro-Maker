function loadMoreAUs() {
    const grid = document.getElementById('moreAusGrid');
    if (!grid) return;

    grid.innerHTML = '';
    expandedAUIntros.forEach(au => {
        const card = document.createElement('div');
        card.className = 'moreau-card';
        card.innerHTML = `
            <h3>${au.name}</h3>
            <div class="au-concept">
                <strong>Concept:</strong> ${au.concept}<br>
                <p style="margin-top: 10px;">${au.description}</p>
            </div>
            ${au.features ? `
                <div class="au-features">
                    <strong>Features:</strong>
                    <ul>
                        ${au.features.map(f => `<li>${f}</li>`).join('')}
                    </ul>
                </div>
            ` : ''}
            <div class="au-lyrics-preview">
                <strong>Lyrics Preview:</strong><br>
                ${au.lyrics.slice(0, 3).map(line => `<div>${line}</div>`).join('')}
                ${au.lyrics.length > 3 ? '<div style="margin-top: 8px; opacity: 0.7;">...and more!</div>' : ''}
            </div>
        `;
        card.addEventListener('click', () => selectMoreAU(au));
        grid.appendChild(card);
    });
}


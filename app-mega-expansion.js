function selectMoreAU(au) {
    if (typeof currentIntro !== 'undefined') {
        currentIntro = {
            type: 'moreau',
            data: au
        };
    }

    if (typeof updateNowPlaying === 'function') {
        updateNowPlaying(au.name);
    }

    if (typeof displayLyrics === 'function') {
        displayLyrics(au.lyrics);
    }
}


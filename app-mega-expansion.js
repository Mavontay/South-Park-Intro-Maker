function generateAdvancedTheme() {
    const tempo = document.getElementById('tempoSelect').value;
    const pitch = document.getElementById('pitchSelect').value;
    const effects = document.getElementById('effectsSelect').value;
    const style = document.getElementById('styleGenSelect').value;

    const output = document.getElementById('themeGenOutput');

    const tempoData = themeSongVariations.tempoChanges.find(t => t.speed == tempo);
    const pitchData = themeSongVariations.pitchVariations.find(p => p.pitch == pitch);
    const effectData = themeSongVariations.effectCombinations.find(e => e.name === effects);
    const styleData = introStyleGenerators.find(s => s.id === style);

    let htmlOutput = `
        <div class="generated-theme">
            <h2 style="color: #1976d2; margin-bottom: 20px;">🎵 Your Custom Theme Song</h2>
    `;

    if (tempoData) {
        htmlOutput += `
            <div style="background: white; padding: 15px; border-radius: 8px; margin-bottom: 15px;">
                <strong>⏱️ Tempo:</strong> ${tempoData.name}<br>
                <span style="color: #666;">Speed: ${tempoData.speed}x - ${tempoData.description}</span>
            </div>
        `;
    }

    if (pitchData) {
        htmlOutput += `
            <div style="background: white; padding: 15px; border-radius: 8px; margin-bottom: 15px;">
                <strong>🎹 Pitch:</strong> ${pitchData.name}<br>
                <span style="color: #666;">Shift: ${pitchData.pitch > 0 ? '+' : ''}${pitchData.pitch} semitones - ${pitchData.description}</span>
            </div>
        `;
    }

    if (effectData) {
        htmlOutput += `
            <div style="background: white; padding: 15px; border-radius: 8px; margin-bottom: 15px;">
                <strong>🎛️ Effects:</strong> ${effectData.name}<br>
                <span style="color: #666;">${effectData.description}</span><br>
                <div style="margin-top: 10px;">
                    ${effectData.effects.map(e => `<span style="background: #e3f2fd; padding: 4px 10px; border-radius: 12px; margin: 3px; display: inline-block;">${e}</span>`).join('')}
                </div>
            </div>
        `;
    }

    if (styleData) {
        htmlOutput += `
            <div style="background: white; padding: 15px; border-radius: 8px; margin-bottom: 15px;">
                <strong>🎸 Style:</strong> ${styleData.name}<br>
                <span style="color: #666;">${styleData.style} - ${styleData.description}</span>
                <div style="margin-top: 10px;">
                    <strong>Characteristics:</strong>
                    <ul style="margin-left: 20px; margin-top: 5px; color: #666;">
                        ${styleData.characteristics.map(c => `<li>${c}</li>`).join('')}
                    </ul>
                </div>
            </div>
        `;
    }

    if (!tempo && !pitch && !effects && !style) {
        htmlOutput += `
            <div style="text-align: center; padding: 40px; color: #999;">
                <p style="font-size: 1.2em;">Select options from the controls to generate your custom theme song!</p>
            </div>
        `;
    } else {
        htmlOutput += `
            <div style="background: linear-gradient(135deg, #4caf50 0%, #8bc34a 100%); color: white; padding: 20px; border-radius: 8px; text-align: center;">
                <h3>✅ Theme Song Generated Successfully!</h3>
                <p style="margin-top: 10px;">Your custom combination is ready to play!</p>
                <button class="btn-generate" style="margin-top: 15px; background: white; color: #4caf50;" onclick="playCustomTheme()">
                    ▶️ Play Custom Theme
                </button>
            </div>
        `;
    }

    htmlOutput += '</div>';
    output.innerHTML = htmlOutput;
}

